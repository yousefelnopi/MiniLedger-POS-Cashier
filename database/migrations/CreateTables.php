<?php

namespace App\Database\Migrations;

use App\Core\Database;

class CreateTables
{
    private Database $db;

    public function __construct()
    {
        $this->db = Database::getInstance();
    }

    // ─── Run all migrations ───────────────────────────────────────────
    public function run(): void
    {
        $this->createUsers();
        $this->createCategories();
        $this->createProducts();
        $this->createCustomers();
        $this->createCarModels();
        $this->createCarModelProduct();
        $this->createInvoices();
        $this->createInvoiceItems();
        $this->createSyncLog();
    }

    // ─── Users ────────────────────────────────────────────────────────
    private function createUsers(): void
    {
        $this->db->execute("
            CREATE TABLE IF NOT EXISTS users (
                id         INTEGER PRIMARY KEY AUTOINCREMENT,
                api_id     INTEGER NOT NULL UNIQUE,
                name       TEXT    NOT NULL,
                email      TEXT    NOT NULL UNIQUE,
                created_at TEXT    NOT NULL DEFAULT (datetime('now'))
            )
        ");
    }

    /**
     * Note:
        api_id  → Represents the resource ID coming from the remote server API.
        id      → Represents the local database ID generated by SQLite for internal use within the POS system.
     */

    // ─── Categories ───────────────────────────────────────────────────
    private function createCategories(): void
    {
        $this->db->execute("
            CREATE TABLE IF NOT EXISTS categories (
                id         INTEGER PRIMARY KEY AUTOINCREMENT,
                api_id     INTEGER NOT NULL UNIQUE,
                name       TEXT    NOT NULL,
                image TEXT,
                created_at TEXT    NOT NULL DEFAULT (datetime('now'))
            )
        ");
    }

    // ─── Products ─────────────────────────────────────────────────────
    private function createProducts(): void
    {
        $this->db->execute("
            CREATE TABLE IF NOT EXISTS products (
                id            INTEGER PRIMARY KEY AUTOINCREMENT,
                api_id        INTEGER NOT NULL UNIQUE,
                category_id   INTEGER,
                name          TEXT    NOT NULL,
                sku           TEXT    NOT NULL,
                part_number   TEXT,
                image TEXT,
                sell_price    REAL    NOT NULL DEFAULT 0,
                stock_qty     INTEGER NOT NULL DEFAULT 0,
                alert_stock   INTEGER NOT NULL DEFAULT 0,
                location_code TEXT,
                is_active     INTEGER NOT NULL DEFAULT 1,
                created_at    TEXT    NOT NULL DEFAULT (datetime('now')),
                FOREIGN KEY (category_id) REFERENCES categories(id)
            )
        ");
    }

    // ─── Customers ────────────────────────────────────────────────────
    private function createCustomers(): void
    {
        $this->db->execute("
        CREATE TABLE IF NOT EXISTS customers (
            id         INTEGER PRIMARY KEY AUTOINCREMENT,
            api_id     INTEGER UNIQUE,
            name       TEXT    NOT NULL,
            phone      TEXT,
            created_at TEXT    NOT NULL DEFAULT (datetime('now'))
        )
    ");
    }

    // ─── Car Models ───────────────────────────────────────────────────
    private function createCarModels(): void
    {
        $this->db->execute("
            CREATE TABLE IF NOT EXISTS car_models (
                id         INTEGER PRIMARY KEY AUTOINCREMENT,
                api_id     INTEGER NOT NULL UNIQUE,
                brand      TEXT    NOT NULL,
                model      TEXT    NOT NULL,
                year       INTEGER,
                engine     TEXT,
                trim       TEXT,
                created_at TEXT    NOT NULL DEFAULT (datetime('now'))
            )
        ");
    }

    // ─── Car Model Product (pivot) ────────────────────────────────────
    private function createCarModelProduct(): void
    {
        $this->db->execute("
            CREATE TABLE IF NOT EXISTS car_model_product (
                car_model_id INTEGER NOT NULL,
                product_id   INTEGER NOT NULL,
                PRIMARY KEY (car_model_id, product_id),
                FOREIGN KEY (car_model_id) REFERENCES car_models(id),
                FOREIGN KEY (product_id)   REFERENCES products(id)
            )
        ");
    }

    // ─── Invoices ─────────────────────────────────────────────────────
    private function createInvoices(): void
    {
        $this->db->execute("
            CREATE TABLE IF NOT EXISTS invoices (
                id             INTEGER PRIMARY KEY AUTOINCREMENT,
                uuid           TEXT    NOT NULL UNIQUE,
                cashier_email  TEXT    NOT NULL,
                customer_id    INTEGER,
                discount       REAL    NOT NULL DEFAULT 0,
                tax            REAL    NOT NULL DEFAULT 0,
                total_amount   REAL    NOT NULL DEFAULT 0,
                type           TEXT    NOT NULL DEFAULT 'sale',
                is_synced      INTEGER NOT NULL DEFAULT 0,
                created_at     TEXT    NOT NULL DEFAULT (datetime('now')),
                FOREIGN KEY (customer_id) REFERENCES customers(id)
            )
        ");
    }

    // ─── Invoice Items ────────────────────────────────────────────────
    private function createInvoiceItems(): void
    {
        $this->db->execute("
            CREATE TABLE IF NOT EXISTS invoice_items (
                id           INTEGER PRIMARY KEY AUTOINCREMENT,
                invoice_id   INTEGER NOT NULL,
                product_id   INTEGER NOT NULL,
                product_name TEXT    NOT NULL,
                quantity     INTEGER NOT NULL DEFAULT 1,
                unit_price   REAL    NOT NULL DEFAULT 0,
                total_row    REAL    NOT NULL DEFAULT 0,
                created_at   TEXT    NOT NULL DEFAULT (datetime('now')),
                FOREIGN KEY (invoice_id) REFERENCES invoices(id),
                FOREIGN KEY (product_id) REFERENCES products(id)
            )
        ");
    }

    // ─── Sync Log ─────────────────────────────────────────────────────
    private function createSyncLog(): void
    {
        $this->db->execute("
            CREATE TABLE IF NOT EXISTS sync_log (
                id              INTEGER PRIMARY KEY AUTOINCREMENT,
                invoice_uuid    TEXT    NOT NULL UNIQUE,
                status          TEXT    NOT NULL DEFAULT 'pending',
                error_message   TEXT,
                attempts        INTEGER NOT NULL DEFAULT 0,
                last_attempt_at TEXT,
                created_at      TEXT    NOT NULL DEFAULT (datetime('now')),
                FOREIGN KEY (invoice_uuid) REFERENCES invoices(uuid)
            )
        ");
    }
}

/*
Local SQLite Tables

users
    Stores cashier data after login.
    Fields: api_id, name, email

categories
    Stores product categories synced from the server.
    Fields: api_id, name

products
    Stores product data received from the API.
    Fields: api_id + all product attributes except buy_price
    (buy_price is intentionally excluded for security reasons).

customers
    Stores customer records.
    Fields: api_id, name, phone

car_models
    Stores vehicle models used for compatibility matching.
    Fields: api_id, brand, model, year, engine, trim

car_model_product
    Pivot table representing the many-to-many relationship
    between products and compatible car models.

invoices
    Stores locally created invoices before or after sync.
    Fields: cashier_email, uuid, type, is_synced

invoice_items
    Stores invoice line items.
    Fields: product_id, quantity, unit_price, total_row

sync_log
    Tracks synchronization attempts with the server.
    Fields: invoice_uuid, status, attempts
*/
// ```

